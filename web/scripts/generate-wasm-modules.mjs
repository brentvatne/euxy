/**
 * Emits the binaries the on-demand OG route needs as base64 *source* modules.
 *
 * Why source and not assets: Metro has no wasm handling at all (it's in
 * neither assetExts nor sourceExts as of Metro 0.84). Forcing wasm into
 * assetExts makes the import resolve to a URL string and the file is never
 * emitted — the URL 404s. A base64 string in a .ts file is just source, so it
 * always bundles.
 *
 * The consumer compiles these at module top-level, which is the only scope
 * where the Workers runtime permits wasm codegen — request-time
 * WebAssembly.compile throws "Wasm code generation disallowed by embedder".
 * Instantiating an already-compiled Module per request is fine.
 *
 * Output is gitignored; `bun run og:wasm` is chained into export/deploy.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const outDir = join(root, 'lib', 'generated');
mkdirSync(outDir, { recursive: true });

const SOURCES = [
  { name: 'resvg-wasm', from: 'node_modules/@resvg/resvg-wasm/index_bg.wasm', export: 'RESVG_WASM_B64' },
  { name: 'yoga-wasm', from: 'node_modules/satori/yoga.wasm', export: 'YOGA_WASM_B64' },
  { name: 'font-regular', from: 'assets/og-fonts/SpaceMono-Regular.ttf', export: 'SPACE_MONO_REGULAR_B64' },
  { name: 'font-bold', from: 'assets/og-fonts/SpaceMono-Bold.ttf', export: 'SPACE_MONO_BOLD_B64' },
];

let total = 0;
for (const src of SOURCES) {
  const bytes = readFileSync(join(root, src.from));
  const b64 = bytes.toString('base64');
  total += b64.length;
  writeFileSync(
    join(outDir, `${src.name}.ts`),
    `// @generated by scripts/generate-wasm-modules.mjs — do not edit, do not commit.\n` +
      `export const ${src.export} = '${b64}';\n`,
  );
  console.log(
    `  ${src.name.padEnd(14)} ${(bytes.length / 1024).toFixed(0).padStart(5)} KB → ` +
      `${(b64.length / 1024).toFixed(0).padStart(5)} KB base64`,
  );
}
console.log(`generated 4 modules → lib/generated/ (${(total / 1048576).toFixed(2)} MB of source)`);
